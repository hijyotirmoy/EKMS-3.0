async function run() {
  console.log(`Starting restoration of ${restoredAppointments.length} appointments...`);

  // 1. Post to /api/v1/appointments via HTTP REST API
  for (const appt of restoredAppointments) {
    try {
      const res = await fetch("http://localhost:3000/api/v1/appointments", {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
          "x-api-key": "ekms_live_triage_8f94d2e1b7c041a693e5a2",
        },
        body: JSON.stringify({
          ...appt,
          source: "Restoration Script",
          _skipSheetWebhook: true,
        }),
      });
      const data = await res.json();
      console.log(`Saved ${appt.tokenNo} (${appt.patientName}):`, data.success ? "OK" : data.error);
    } catch (e) {
      console.warn(`Error saving ${appt.tokenNo}:`, e.message);
    }
  }

  // 2. Sync to /api/google-sheets/record
  for (const appt of restoredAppointments) {
    try {
      const res = await fetch("http://localhost:3000/api/google-sheets/record", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          timestamp: appt.bookedAt || "27/11/2026, 12:00 pm",
          record_type: "Booking Done",
          case_id: appt.caseId || "",
          booking_ref_id: appt.tokenNo,
          reference_id: appt.tokenNo,
          caller_id: appt.callerId || "",
          callerId: appt.callerId || "",
          name: appt.patientName,
          phone_no: appt.phone,
          ip_no: appt.ipNo || "N/A",
          date_time: `${appt.date} ${appt.timeSlot || ""}`.trim(),
          dispensary_name: appt.dispensaryName,
          agent_name: appt.bookedByName || "Triage Desk",
          chief_complaint: appt.chiefComplaint || "",
          status: appt.status === "with_doctor" ? "With Doctor" : (appt.status === "completed" ? "Completed" : "Booking Confirmed"),
          reception_by: appt.receptionCheckedInBy ? `Reception by ${appt.receptionCheckedInBy}, ${appt.receptionCheckedInAt}` : "—",
          is_status_update: false,
        }),
      });
      const data = await res.json();
      console.log(`Google Sheets record for ${appt.tokenNo} (${appt.patientName}):`, data.success ? "OK" : data.detail);
    } catch (e) {
      console.warn(`Error recording to sheet ${appt.tokenNo}:`, e.message);
    }
  }

  console.log("Restoration complete!");
}

run();
